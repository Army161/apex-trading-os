// Strategy and engine fingerprints (docs/design/04 s2). Node only: not exported from index.ts, so the web bundle never sees fs.
// A strategy's fingerprint is the SHA-256 of the signals it produces on three frozen fixtures. If its behaviour changes, the
// fingerprint changes, the `fingerprints` check fails, and the change shows up in the pull request as a diff of fingerprints.json.
// The fixtures are frozen copies. Never refresh them: that would change every fingerprint at once.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { backtest, type Bar, type Sig } from './core';
import { STRATEGIES, type StratDef } from './strategies';

const FIX = ['fp-spy-30m.csv', 'fp-btc-1d.csv', 'fp-gld-1d.csv'];
const sha = (s: string) => createHash('sha256').update(s).digest('hex');
const r6 = (x: number) => (Number.isFinite(x) ? Number(x.toPrecision(8)) : null);
const bits = (a: boolean[]) => a.map(x => (x ? '1' : '0')).join('');
let cache: Bar[][] | null = null;
export function fixtures(dir = join(__dirname, 'fixtures')): Bar[][] {
  return cache ??= FIX.map(f => readFileSync(join(dir, f), 'utf8').trim().split('\n').slice(1).map(l => { const [t, o, h, lo, c, v] = l.split(',').map(Number); return { t, o, h, l: lo, c, v }; }));
}
const sigDigest = (s: Sig) => sha(JSON.stringify([bits(s.le), bits(s.se), bits(s.lx), bits(s.sx), s.stop.map(r6), s.target.map(r6), s.maxBars ?? null, !!s.fullSize, s.trail ?? null]));

/** A strategy that throws on a fixture still gets a stable fingerprint (the error text is part of it). */
export function strategyFingerprint(def: Pick<StratDef, 'build'>, fx = fixtures()): string {
  return sha(fx.map(b => { try { return sigDigest(def.build(b)); } catch (e) { return `error:${(e as Error).message}`; } }).join('|'));
}
/** Changes when fill logic changes: every trade and the final equity of three reference strategies on the fixtures. */
export function engineFingerprint(fx = fixtures()): string {
  const refs = ['turtle_55_20', 'sma50_trend', 'rsi2_dip'].map(id => STRATEGIES.find(s => s.id === id)!);
  return sha(JSON.stringify(fx.map(b => refs.map(s => { const r = backtest(b, s.build(b)); return [r.trades.map(t => [t.entryT, t.exitT, t.side, r6(t.entry), r6(t.exit), r6(t.qty), r6(t.pnl), t.reason]), r6(r.equity[r.equity.length - 1])]; }))));
}
export type Fingerprints = { note: string; engine: string; strategies: Record<string, string> };
export function computeFingerprints(defs: StratDef[] = STRATEGIES): Fingerprints {
  return { note: 'Generated by `npm run apex -- strategies fingerprint --write`. A diff here means behaviour changed. Review it; never hand-edit.', engine: engineFingerprint(),
    strategies: Object.fromEntries([...defs].sort((a, b) => (a.id < b.id ? -1 : 1)).map(s => [s.id, strategyFingerprint(s)])) };
}
export function diffFingerprints(committed: Fingerprints, now: Fingerprints): string[] {
  const out: string[] = []; if (committed.engine !== now.engine) out.push('engine: fill logic changed');
  for (const id of new Set([...Object.keys(committed.strategies), ...Object.keys(now.strategies)])) {
    const a = committed.strategies[id], b = now.strategies[id];
    if (!a) out.push(`${id}: new strategy, not in fingerprints.json`); else if (!b) out.push(`${id}: removed from the registry`); else if (a !== b) out.push(`${id}: signals changed`);
  }
  return out;
}
